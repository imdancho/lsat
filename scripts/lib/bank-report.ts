import { FLAW_TAG_INFO, QUESTION_TYPE_INFO, TRAP_TAG_INFO } from "@/lib/taxonomy";
import { QUESTION_TYPES, type Question } from "@/lib/types";
import {
  countWords,
  hasSpeakerLabel,
  hasTwoSpeakers,
  isCorrectLongest,
  tally,
} from "./bank-stats";

/** Hand-maintained notes that cannot be computed from the bank (data/review-log.json). */
export type ReviewLog = {
  /** Where the main conclusion sits in each stimulus, tallied by hand. */
  conclusionPlacement: { first: number; middle: number; end: number };
  blindCheck: {
    method: string;
    rounds: {
      label: string;
      solved: number;
      matchedKey: number;
      markedAmbiguous: number;
      notes: string;
    }[];
    rewritten: { id: string; change: string }[];
    outcome: string;
  };
};

const table = (head: string[], rows: (string | number)[][]) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");

const sorted = <T extends string | number>(counts: Map<T, number>) =>
  [...counts.entries()].sort((a, b) => b[1] - a[1]);

export function buildReport(bank: Question[], log: ReviewLog): string {
  const blind = log.blindCheck;
  const placement = log.conclusionPlacement;
  const words = bank.map((q) => countWords(q.stimulus)).sort((a, b) => a - b);
  const labelled = bank.filter((q) => hasSpeakerLabel(q.stimulus)).length;
  const exchanges = bank.filter((q) => hasTwoSpeakers(q.stimulus)).length;
  const longest = bank.filter(isCorrectLongest).length;

  const typeRows = QUESTION_TYPES.map((type) => {
    const ofType = bank.filter((q) => q.type === type);
    const byLevel = [1, 2, 3].map(
      (d) => ofType.filter((q) => q.difficulty === d).length,
    );
    return [QUESTION_TYPE_INFO[type].label, ...byLevel, ofType.length];
  });

  const indexRows = [0, 1, 2, 3, 4].map((i) => [
    "ABCDE"[i],
    bank.filter((q) => q.correctIndex === i).length,
    bank.filter((q) => q.mostTempting === i).length,
  ]);

  const flawRows = sorted(
    tally(bank.map((q) => q.key.flawTag).filter((t) => t !== "none")),
  ).map(([tag, n]) => [FLAW_TAG_INFO[tag].label, n]);

  const trapRows = sorted(
    tally(bank.flatMap((q) => q.choiceTraps).filter((t) => t !== "correct")),
  ).map(([tag, n]) => [TRAP_TAG_INFO[tag].label, n]);

  const topicRows = QUESTION_TYPES.map((type) => [
    QUESTION_TYPE_INFO[type].label,
    bank
      .filter((q) => q.type === type)
      .map((q) => q.topic)
      .join("; "),
  ]);

  return `# Question bank report

Generated by \`npx tsx scripts/validate-questions.ts --report\` from \`data/questions.json\`.
Do not edit by hand; the hand-kept notes come from \`data/review-log.json\`.

The bank holds **${bank.length} original LSAT-style Logical Reasoning questions**, written to
\`docs/lsat-style-guide.md\`. No official LSAT text or topic is used.

## Questions by type and difficulty

${table(["Type", "Easy", "Medium", "Hard", "Total"], typeRows)}

## Answer key balance

${table(["Letter", "Correct answer", "Most tempting wrong answer"], indexRows)}

The correct answer is the longest choice in ${longest} of ${bank.length} questions (style guide: at most about 1 in 3).

## Reasoning flaws tested

Main Conclusion questions test structure, not a flaw, so they are not counted here.

${table(["Flaw built into the argument", "Questions"], flawRows)}

## Wrong-answer traps

Every wrong choice carries one trap tag, and the four wrong choices of a question all differ.

${table(["Trap", "Choices"], trapRows)}

## Stimuli

- Length: ${words[0]}–${words[words.length - 1]} words, median ${words[Math.floor(words.length / 2)]} (style guide: 55–110).
- Speaker label: ${labelled} of ${bank.length} (target about half); ${exchanges} are two-speaker exchanges.
- Main conclusion placed first in ${placement.first}, in the middle in ${placement.middle}, at the end in ${placement.end} (target about 30% / 30% / 40%).
- ${new Set(bank.map((q) => q.topic)).size} distinct topics, one per question.

${table(["Type", "Topics"], topicRows)}

## Blind self-check

${blind.method}

${table(
  ["Round", "Questions solved", "Matched the key", "Marked ambiguous", "Notes"],
  blind.rounds.map((r) => [r.label, r.solved, r.matchedKey, r.markedAmbiguous, r.notes]),
)}

**Questions rewritten after the blind check: ${blind.rewritten.length}.**

${blind.rewritten.map((r) => `- \`${r.id}\`: ${r.change}`).join("\n") || "- none"}

${blind.outcome}
`;
}
